import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const sylabiRoot = path.join(root, "public", "sylabi");
const outputPath = path.join(root, "src", "data", "sylabiCatalog.ts");

function humanizeFileName(fileName) {
  const base = fileName.replace(/\.pdf$/i, "").trim();
  if (!base || base === ".pdf") return "Untitled syllabus";

  return base
    .replace(/_/g, " ")
    .replace(/-/g, " ")
    .replace(/([a-z])([A-Z])/g, "$1 $2")
    .replace(/\s+/g, " ")
    .trim();
}

function slugify(value) {
  return value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}

function walkPdfEntries(dir, subject) {
  const entries = [];

  for (const name of fs.readdirSync(dir)) {
    if (name.startsWith(".")) continue;

    const fullPath = path.join(dir, name);
    const stat = fs.statSync(fullPath);

    if (stat.isDirectory()) {
      entries.push(...walkPdfEntries(fullPath, name));
      continue;
    }

    if (!/\.pdf$/i.test(name)) continue;

    const relativePath = path.relative(sylabiRoot, fullPath).split(path.sep).join("/");
    const id = slugify(`${subject}-${name}`);

    entries.push({
      id,
      subject,
      title: humanizeFileName(name),
      fileName: name,
      pdfPath: `/sylabi/${relativePath}`,
    });
  }

  return entries;
}

if (!fs.existsSync(sylabiRoot)) {
  console.error(`Missing ${sylabiRoot}`);
  process.exit(1);
}

const entries = [];

for (const name of fs.readdirSync(sylabiRoot)) {
  if (name.startsWith(".") || name === "manifest.jsonl") continue;

  const fullPath = path.join(sylabiRoot, name);
  if (!fs.statSync(fullPath).isDirectory()) continue;

  entries.push(...walkPdfEntries(fullPath, name));
}

entries.sort((a, b) => {
  const subject = a.subject.localeCompare(b.subject);
  if (subject !== 0) return subject;
  return a.title.localeCompare(b.title);
});

const subjects = [...new Set(entries.map((entry) => entry.subject))].sort();

const fileContents = `/** Auto-generated by npm run catalog:sylabi — do not edit manually. */
export interface SylabiCatalogEntry {
  id: string;
  subject: string;
  title: string;
  fileName: string;
  pdfPath: string;
}

export const sylabiCatalogSubjects: string[] = ${JSON.stringify(subjects, null, 2)};

export const sylabiCatalog: SylabiCatalogEntry[] = ${JSON.stringify(entries, null, 2)};
`;

fs.writeFileSync(outputPath, fileContents);
console.log(`Wrote ${entries.length} entries across ${subjects.length} subjects to ${outputPath}`);
